// ---------------------------------------------------------------------------
// k6 load test of the BFF Project.
//
// Every operation of the contract (contracts/openapi.json, mounted as /openapi.json) has one
// handler below: the shared OpenAPI coverage module (mairie360/CICD tests/k6/coverage.js, see
// performance_test.sh) aborts at init when an operation has no handler, and fails the
// `operations_uncovered` threshold when a handler ends without sending its request. Adding a route
// to the BFF therefore means adding its handler here.
//
// Two scenarios share the handlers:
// - `crud` (the crud VUs of the profile): `coverage.run()` calls every handler once per iteration, reads and writes, so
//   it carries the coverage gate. Handlers run path by path in contract order and, for one path,
//   in the order get, put, post, delete, options, head, patch, trace, so `PATCH .../close` runs
//   before `POST /projects`. `prepare()` therefore creates the working project (with one task)
//   before the handlers run; the POST handlers create the disposable project and task that the
//   DELETE handlers remove, and `cleanup()` deletes the working project and its duplicate. The status and template
//   handlers (MAIR-566) follow the same pattern: POST creates the disposable status / template that DELETE removes,
//   PATCH works on a status of the working project / on the working template that `prepare()` creates.
// - `reads` (up to the read VUs of the profile): replays only the GET handlers, which read the rows
//   seeded by init-perf.sql and never depend on `state`.
// - `page_rush`: `GET /projects-page` as seeded agents at a fixed arrival rate, failing if k6 has to
//   drop iterations.
// Every operation gets a p(95) threshold, whose budget depends on its family (`budgetOf`).
//
// MAIR-474: the stack also runs init-perf.sql (Project_API's volume seed: 5 000 projects, 50 000
// tasks, 2 100 accounts in 100 teams, the hot project 12 with 2 000 tasks (200 active, 1 800 archived) and the task 87 with 1 000
// comments and history entries). The reads run as the Admin, a seeded Responsable or a seeded agent,
// every read checks that it got the seeded rows, and the thresholds are strict (every check passes,
// no failed request, no dropped iteration). K6_PROFILE sizes the load: `ci` (default) is what the
// 4 vCPU CI runner holds, `stress` is the high load, run by hand.
// ---------------------------------------------------------------------------

// The JWT_SECRET of the stack: random per run, generated by stack_secrets.sh (MAIR-474). No default:
